def req(name, method, path, body=None, auth=False, tests=None, prerequest=None, desc="", query=None, form=None,
        token="accessToken"):
    """auth=True sends Bearer {{token}}. query: list of (key, value) or (key, value, True) for a disabled parameter.
    form: multipart fields, (key, None) is a file field picked in Postman, (key, value) a text field."""
    raw = "{{baseUrl}}" + path
    url = {"raw": raw, "host": ["{{baseUrl}}"], "path": path.strip("/").split("/")}
    if query:
        url["query"] = [{"key": q[0], "value": q[1], **({"disabled": True} if len(q) > 2 and q[2] else {})} for q in query]
        url["raw"] = raw + "?" + "&".join(f"{q[0]}={q[1]}" for q in query if not (len(q) > 2 and q[2]))
    item = {
        "name": name,
        "request": {
            "method": method,
            "header": [{"key": "Content-Type", "value": "application/json"}] if body is not None else [],
            "url": url,
            "description": desc,
            "auth": {"type": "bearer", "bearer": [{"key": "token", "value": "{{" + token + "}}", "type": "string"}]}
            if auth else {"type": "noauth"},
        },
        "event": [],
    }
    if form is not None:
        item["request"]["body"] = {"mode": "formdata", "formdata": [
            {"key": key, "type": "file", "src": []} if value is None else {"key": key, "value": value, "type": "text"}
            for key, value in form]}
    if body is not None:
        item["request"]["body"] = {"mode": "raw", "raw": json.dumps(body, ensure_ascii=False, indent=2),
                                   "options": {"raw": {"language": "json"}}}
    if prerequest:
        item["event"].append({"listen": "prerequest", "script": {"type": "text/javascript", "exec": prerequest}})
    if tests:
        item["event"].append({"listen": "test", "script": {"type": "text/javascript", "exec": tests}})
    return item


def expect_error(status, code=None):
    lines = [
        f"pm.test('HTTP {status}', () => pm.response.to.have.status({status}));",
        "const body = pm.response.json();",
        "pm.test('Envelope lỗi', () => { pm.expect(body.success).to.eql(false); pm.expect(body.traceId).to.be.a('string'); });",
    ]
    if code:
        lines.append(f"pm.test('Mã lỗi {code}', () => pm.expect(body.errors[0].code).to.eql('{code}'));")
    return lines



def cookie_mode(item):
    """Web session in an HttpOnly cookie (docs/specs/auth.md, BE-1): Postman keeps the cookie in its jar."""
    item["request"]["header"].append({"key": "X-Auth-Transport", "value": "cookie"})
    return item

