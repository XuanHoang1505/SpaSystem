def expect_field_error(field):
    # Validation errors carry a per-field code (e.g. NotEmptyValidator), so only the status and field are checked.
    return expect_error(400) + [
        f"pm.test('Lỗi ở trường {field}', () => pm.expect(body.errors.map(e => e.field)).to.include('{field}'));"]


def expect_ok(status=200, save=None, extra=None):
    """save: {environment variable: JS expression on body}."""
    lines = [
        f"pm.test('HTTP {status}', () => pm.response.to.have.status({status}));",
        "const body = pm.response.json();",
        "pm.test('Envelope thành công', () => pm.expect(body.success).to.eql(true));",
    ]
    lines += extra or []
    lines += [f"pm.environment.set('{key}', {expression});" for key, expression in (save or {}).items()]
    return lines


